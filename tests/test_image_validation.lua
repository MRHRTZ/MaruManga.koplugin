local validator = dofile("reader/image_validation.lua")
assert(validator.validate("image/jpeg; charset=binary", 100, "\255\216\255x") == "jpg")
assert(validator.validate("image/png", 100, "\137PNG\r\n\26\n") == "png")
assert(validator.validate("image/gif", 100, "GIF89a") == "gif")
assert(validator.validate("image/webp", 100, "RIFF1234WEBP") == "webp")
assert(not validator.validate("text/html", 100, "<html>"))
assert(not validator.validate("image/png", 100, "GIF89a"))
assert(not validator.validate("image/png", 0, "\137PNG\r\n\26\n"))
assert(not validator.validate("image/jpeg", 21, "\255\216\255", 20))
print("Image validation tests passed")
